-- 1. Extensions ---------------------------------------------------------------
CREATE EXTENSION IF NOT EXISTS vector;

-- 2. Tables -------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS chat_message (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp(6) with time zone NOT NULL,
    author     varchar(128) NOT NULL,
    message    text         NOT NULL,
    embedding  vector(1536)
);

-- Tasks the bot executes on a schedule. `schedule` is a Spring 6-field cron
-- expression (second minute hour day-of-month month day-of-week).
CREATE TABLE IF NOT EXISTS scheduled_task (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              varchar(128) NOT NULL,
    prompt            text         NOT NULL,
    schedule          varchar(128) NOT NULL,
    status            varchar(16)  NOT NULL CHECK (status IN ('ENABLED', 'DISABLED')),
    last_execution_at timestamp(6) with time zone,
    remaining_count   integer CHECK (remaining_count IS NULL OR remaining_count >= 0),
    created_at        timestamp(6) with time zone NOT NULL DEFAULT now()
);

-- Migration for databases created before remaining_count existed.
-- NULL = unlimited; otherwise runs left, the task is disabled when it reaches 0.
ALTER TABLE scheduled_task
    ADD COLUMN IF NOT EXISTS remaining_count integer CHECK (remaining_count IS NULL OR remaining_count >= 0);

-- 3. Indexes ------------------------------------------------------------------
CREATE UNIQUE INDEX IF NOT EXISTS idx_scheduled_task_name
    ON scheduled_task (name);

-- Approximate-nearest-neighbour index for cosine similarity search
-- (matches the `embedding <=> :q` operator used in ChatMessageRepository).
CREATE INDEX IF NOT EXISTS idx_chat_message_embedding_hnsw
    ON chat_message
    USING hnsw (embedding vector_cosine_ops);

-- Common access patterns: recent messages, per-author history.
CREATE INDEX IF NOT EXISTS idx_chat_message_created_at
    ON chat_message (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_chat_message_author_created_at
    ON chat_message (author, created_at DESC);

